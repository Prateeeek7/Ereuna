"""Stage 8: Experiments — suggest experiments that address the map's research gaps.

Suggestions are generated by the configured LLM from the gap statements, the
supporting papers' verified methods and limitations, and the tools actually
used in this corpus. Without an LLM no experiments are produced: a protocol
is a design proposal, and templated protocols would be fabricated content.
"""

import logging
from typing import Optional

from pydantic import BaseModel, Field

from app.clients.llm import LlmClient
from app.models.map import Experiment, Gap, ToolEntry
from app.models.paper import Paper

logger = logging.getLogger(__name__)

MAX_EXPERIMENTS = 5


class _LlmExperiment(BaseModel):
    gap_id: str = Field(description="The gap id this experiment addresses (e.g. gap_1)")
    hypothesis: str = Field(description="A falsifiable hypothesis")
    setup: str = Field(description="How to run the experiment, building on the cited papers' methods")
    tools: list[str] = Field(default_factory=list, description="Tools/datasets to use, preferring ones from the corpus list")
    variables: list[str] = Field(default_factory=list, description="Independent variables and their ranges")
    expected_result: str = Field(description="What to measure and what outcome would confirm or refute the hypothesis")
    difficulty: str = Field(description="LOW, MED, or HIGH")


class _LlmExperimentResponse(BaseModel):
    experiments: list[_LlmExperiment] = Field(default_factory=list)


def _paper_context(paper: Paper) -> str:
    ext = paper.extraction
    lines = [f"- {paper.short_label or paper.title[:40]} ({paper.year}): {paper.title}"]
    if ext and ext.method:
        lines.append(f"  method: {ext.method.text}")
    if ext:
        for lim in ext.limitations[:2]:
            lines.append(f"  stated limitation: {lim.text}")
    return "\n".join(lines)


async def suggest_experiments(
    gaps: list[Gap],
    papers: list[Paper],
    tools: Optional[list[ToolEntry]] = None,
    topic: str = "",
    llm: Optional[LlmClient] = None,
) -> list[Experiment]:
    """Generate experiment suggestions for the identified gaps (LLM required)."""
    if not gaps:
        return []
    if llm is None or not llm.is_configured():
        logger.info("Stage 8 skipped: experiment suggestions require an LLM")
        return []

    papers_by_id = {p.id: p for p in papers}
    gap_blocks: list[str] = []
    for gap in gaps[:MAX_EXPERIMENTS]:
        support = [papers_by_id[pid] for pid in gap.supporting_paper_ids if pid in papers_by_id][:3]
        context = "\n".join(_paper_context(p) for p in support)
        gap_blocks.append(
            f"{gap.id}: {gap.statement}\n  evidence: {gap.pattern}\n  supporting papers:\n{context}"
        )
    tool_names = ", ".join(t.name for t in (tools or [])[:25]) or "none extracted"

    prompt = f"""Research topic: {topic}

Research gaps identified in this literature map:
{chr(10).join(gap_blocks)}

Tools and datasets used across the papers: {tool_names}

For each gap, propose one concrete experiment that would help close it. Build on the supporting
papers' methods. Do not state results as facts; expected_result describes what to measure and what
outcome would support or refute the hypothesis. Do not cite papers or numbers that are not above.
"""
    try:
        resp = await llm.structured(prompt, _LlmExperimentResponse)
    except Exception as e:
        logger.warning("Experiment suggestion failed: %s", e)
        return []

    gaps_by_id = {g.id: g for g in gaps}
    experiments: list[Experiment] = []
    used_gaps: set[str] = set()
    for item in resp.experiments:
        gap = gaps_by_id.get(item.gap_id.strip())
        if gap is None or gap.id in used_gaps or not item.hypothesis.strip():
            continue
        used_gaps.add(gap.id)
        difficulty = item.difficulty.strip().upper()
        experiments.append(
            Experiment(
                id=f"exp_{len(experiments) + 1}",
                gap_id=gap.id,
                hypothesis=item.hypothesis.strip(),
                setup=item.setup.strip(),
                tools=[t.strip() for t in item.tools if t.strip()],
                variables=[v.strip() for v in item.variables if v.strip()],
                expected_result=item.expected_result.strip(),
                difficulty=difficulty if difficulty in ("LOW", "MED", "HIGH") else "MED",
                paper_ids=gap.supporting_paper_ids[:3],
            )
        )

    logger.info("Stage 8 complete: generated %d experiment suggestions", len(experiments))
    return experiments
